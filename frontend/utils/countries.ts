/** Ghana first, since most orders are domestic; everyone else alphabetically. */
export function countryOptions(locale = 'en'): { value: string, label: string }[] {
  const others = ISO_CODES
    .filter((code) => code !== 'GH')
    .map((code) => ({ value: code, label: countryName(code, locale) }))
    .sort((a, b) => a.label.localeCompare(b.label, locale))

  return [{ value: 'GH', label: countryName('GH', locale) }, ...others]
}

